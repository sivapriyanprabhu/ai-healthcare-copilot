    def handle_risk_assessment(self, req, path=''):
        cond = str(req.get('condition') or req.get('conditionType') or '').lower()
        if not cond:
            if 'diabetes' in path: cond = 'diabetes'
            elif 'hypertension' in path: cond = 'hypertension'
            elif 'stroke' in path: cond = 'stroke'
            elif 'comprehensive' in path: cond = 'comprehensive'
            else: cond = 'heart-disease'

        if 'diabet' in cond:
            return self.handle_diabetes_risk(req)
        elif 'hyper' in cond or 'bp' in cond or 'pressure' in cond:
            return self.handle_hypertension_risk(req)
        elif 'stroke' in cond or 'cerebro' in cond:
            return self.handle_stroke_risk(req)
        elif 'compreh' in cond or 'all' in cond or 'cardio-metabolic' in cond:
            return self.handle_comprehensive_risk(req)
        else:
            return self.handle_heart_risk(req)

