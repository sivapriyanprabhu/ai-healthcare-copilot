    def handle_comprehensive_risk(self, req):
        # Multi-system composite cardio-metabolic assessment
        heart_res = self.handle_heart_risk(req)
        diab_res = self.handle_diabetes_risk(req)
        hyper_res = self.handle_hypertension_risk(req)
        stroke_res = self.handle_stroke_risk(req)

        # Weighted composite score
        comp_score = (
            heart_res['riskScorePercent'] * 0.35 +
            diab_res['riskScorePercent'] * 0.25 +
            hyper_res['riskScorePercent'] * 0.25 +
            stroke_res['riskScorePercent'] * 0.15
        )
        comp_score = round(comp_score, 1)
        risk_cat = "HIGH" if comp_score >= 42.0 else ("MODERATE" if comp_score >= 20.0 else "LOW")

        # Aggregate and pick top factors
        all_factors = heart_res['factors'] + diab_res['factors'] + hyper_res['factors']
        unique_factors = {}
        for f in all_factors:
            key = f['factorName']
            if key not in unique_factors or abs(f['impactScore']) > abs(unique_factors[key]['impactScore']):
                unique_factors[key] = f
        
        sorted_factors = sorted(unique_factors.values(), key=lambda x: abs(x['impactScore']), reverse=True)[:6]

        summary = (
            f"Overall Cardio-Metabolic Health Index indicates a composite score of {comp_score}% ({risk_cat} risk tier). "
            f"Breakdown across systems: Heart Risk: {heart_res['riskScorePercent']}%, Diabetes Risk: {diab_res['riskScorePercent']}%, "
            f"Hypertension: {hyper_res['riskScorePercent']}%, Stroke: {stroke_res['riskScorePercent']}%. "
            f"Holistic lifestyle interventions targeting physical activity and blood pressure will generate multi-system protective benefits."
        )

        return {
            "conditionName": "Comprehensive Cardio-Metabolic Health Index",
            "riskScorePercent": comp_score,
            "riskCategory": risk_cat,
            "confidenceScore": 94.0,
            "summary": summary,
            "factors": sorted_factors,
            "disclaimer": "COMPREHENSIVE MULTI-CONDITION SYNTHESIS: Cross-evaluates cardiovascular, glycemic, arterial, and cerebrovascular markers for personalized preventive wellness."
        }

