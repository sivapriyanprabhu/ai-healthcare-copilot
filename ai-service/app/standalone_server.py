PORT = 8000

class AIServiceHandler(BaseHTTPRequestHandler):
    def _send_cors_headers(self):
        self.send_header('Access-Control-Allow-Origin', '*')
        self.send_header('Access-Control-Allow-Methods', 'GET, POST, OPTIONS')
        self.send_header('Access-Control-Allow-Headers', 'Content-Type, Authorization')

    def do_OPTIONS(self):
        self.send_response(200)
        self._send_cors_headers()
        self.end_headers()

    def do_GET(self):
        if self.path in ['/', '/health']:
            resp = {
                "status": "HEALTHY",
                "service": "AI Healthcare Copilot Clinical AI Engine",
                "version": "1.0.0",
                "port": PORT
            }
            body = json.dumps(resp).encode('utf-8')
            self.send_response(200)
            self.send_header('Content-Type', 'application/json; charset=utf-8')
            self.send_header('Content-Length', str(len(body)))
            self.send_header('Connection', 'close')
            self._send_cors_headers()
            self.end_headers()
            self.wfile.write(body)
        else:
            self.send_response(404)
            self.end_headers()

    def do_POST(self):
        transfer_encoding = self.headers.get('Transfer-Encoding', '').lower()
        if 'chunked' in transfer_encoding:
            chunks = []
            while True:
                line = self.rfile.readline().strip()
                if not line:
                    break
                try:
                    chunk_len = int(line, 16)
                except ValueError:
                    break
                if chunk_len == 0:
                    self.rfile.readline()  # consume trailing \r\n
                    break
                chunk = self.rfile.read(chunk_len)
                chunks.append(chunk)
                self.rfile.readline()  # consume trailing \r\n
            post_data = b''.join(chunks)
        else:
            content_length = int(self.headers.get('Content-Length', 0))
            post_data = self.rfile.read(content_length) if content_length > 0 else b'{}'
        
        try:
            req = json.loads(post_data.decode('utf-8')) if post_data else {}
        except Exception as e:
            req = {}

        path = self.path.rstrip('/')

        if path == '/api/ai/chat':
            resp_data = self.handle_chat(req)
        elif path == '/api/ai/symptoms/analyze':
            resp_data = self.handle_symptoms(req)
        elif path in ['/api/ai/risk/heart-disease', '/api/ai/risk/predict', '/api/ai/risk/diabetes', '/api/ai/risk/hypertension', '/api/ai/risk/stroke', '/api/ai/risk/comprehensive', '/api/ai/risk/assess']:
            resp_data = self.handle_risk_assessment(req, path)
        elif path == '/api/ai/diet/plan':
            resp_data = self.handle_diet(req)
        elif path == '/api/ai/exercise/plan':
            resp_data = self.handle_exercise(req)
        elif path in ['/api/ai/report/analyze', '/api/ai/reports/analyze']:
            resp_data = self.handle_report_analysis(req, post_data)
        elif path == '/api/ai/medications/interactions':
            resp_data = self.handle_drug_interactions(req)
        elif path == '/api/ai/translate':
            resp_data = self.handle_translation(req)
        else:
            self.send_response(404)
            self.end_headers()
            return

        body = json.dumps(resp_data, ensure_ascii=False).encode('utf-8')
        self.send_response(200)
        self.send_header('Content-Type', 'application/json; charset=utf-8')
        self.send_header('Content-Length', str(len(body)))
        self.send_header('Connection', 'close')
        self._send_cors_headers()
        self.end_headers()
        self.wfile.write(body)

